#!/bin/sh
# Wraps a finished meshtown binary into a macOS bundle: <APP_NAME>.app + an archive for distribution.
# It does not build the binary — it only wraps it into the bundle, so it works with any build. The bundle is named
# the same in all calls (<APP_NAME>.app, no architecture in the name) — the caller (platforms/macos/build/
# build.sh) passes different directories for arm64/x86_64/universal, so builds do not overwrite each other.
#
# Usage: platforms/macos/build/app.sh <binary> <output-dir> [archive-suffix]
#   archive-suffix — for example, arm64 → archive <APP_NAME>-macos-arm64.zip; without it — as before,
#                    <APP_NAME>-macos.zip.
#   APP_NAME  — bundle file name (MeshTown.app, no space).
#   APP_TITLE — human-readable name in Info.plist (default Mesh Town).
#   BUNDLE_ID — CFBundleIdentifier (default local.meshtown).
set -e

BIN_PATH="$1"
OUT_DIR="$2"
ZIP_SUFFIX="$3"
APP_NAME="${APP_NAME:-MeshTown}"
APP_TITLE="${APP_TITLE:-Mesh Town}"
BUNDLE_ID="${BUNDLE_ID:-local.meshtown}"

if [ -z "$BIN_PATH" ] || [ -z "$OUT_DIR" ]; then
  echo "usage: $0 <binary> <output-dir> [archive-suffix]" >&2
  exit 1
fi
if [ ! -x "$BIN_PATH" ]; then
  echo "executable not found: $BIN_PATH" >&2
  exit 1
fi
if [ "$(uname -s)" != Darwin ]; then
  echo "the .app bundle is built on a Mac only, this is $(uname -s)" >&2
  exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/../../.." && pwd)"
VERSION="$(sed -n 's/^version = "\(.*\)"/\1/p' "$ROOT/Cargo.toml" | head -1)"
if [ -z "$VERSION" ]; then
  echo "version not found in Cargo.toml" >&2
  exit 1
fi

APP_DIR="$OUT_DIR/$APP_NAME.app"
CONTENTS="$APP_DIR/Contents"
MACOS_DIR="$CONTENTS/MacOS"
RESOURCES="$CONTENTS/Resources"
ICON_NAME="$APP_NAME.icns"

rm -rf "$APP_DIR"
mkdir -p "$MACOS_DIR" "$RESOURCES"

# The main file of the bundle is the binary itself (CFBundleExecutable=meshtown, no separate launcher):
# the process must match CFBundleExecutable, otherwise macOS 26 puts the NSStatusItem icon off
# screen. With no arguments the binary goes to tray (default subcommand substitution); logs are
# ~/Library/Application Support/meshtown/meshtown-tray.log (tray) and meshtown.log (node, the tray
# starts it via current_exe), the previous file of each goes to .1.
cp "$BIN_PATH" "$MACOS_DIR/meshtown"
chmod +x "$MACOS_DIR/meshtown"

# Icon: the source is platforms/macos/build/icon.png (the logo: a ring of sectors with a house on a dark plate, generated by
# generate-icon.py on bare python3), grown into an .iconset with sips, assembled by iconutil.
ICONSET="$OUT_DIR/$APP_NAME.iconset"
rm -rf "$ICONSET"
mkdir -p "$ICONSET"
SRC_ICON="$SCRIPT_DIR/icon.png"
if [ ! -f "$SRC_ICON" ]; then
  echo "icon source not found: $SRC_ICON (run generate-icon.py)" >&2
  exit 1
fi
for spec in "16 icon_16x16.png" "32 icon_16x16@2x.png" "32 icon_32x32.png" \
            "64 icon_32x32@2x.png" "128 icon_128x128.png" "256 icon_128x128@2x.png" \
            "256 icon_256x256.png" "512 icon_256x256@2x.png" "512 icon_512x512.png" \
            "1024 icon_512x512@2x.png"; do
  px="${spec%% *}"
  name="${spec#* }"
  sips -z "$px" "$px" "$SRC_ICON" --out "$ICONSET/$name" >/dev/null
done
iconutil -c icns "$ICONSET" -o "$RESOURCES/$ICON_NAME"
rm -rf "$ICONSET"

# Info.plist
cat > "$CONTENTS/Info.plist" <<PLIST_EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleIdentifier</key>
	<string>$BUNDLE_ID</string>
	<key>CFBundleName</key>
	<string>$APP_TITLE</string>
	<key>CFBundleDisplayName</key>
	<string>$APP_TITLE</string>
	<key>CFBundleExecutable</key>
	<string>meshtown</string>
	<key>CFBundleIconFile</key>
	<string>$ICON_NAME</string>
	<key>CFBundlePackageType</key>
	<string>APPL</string>
	<key>CFBundleShortVersionString</key>
	<string>$VERSION</string>
	<key>CFBundleVersion</key>
	<string>$VERSION</string>
	<key>LSMinimumSystemVersion</key>
	<string>11.0</string>
	<key>LSUIElement</key>
	<true/>
	<key>NSHighResolutionCapable</key>
	<true/>
</dict>
</plist>
PLIST_EOF

# Signing the whole bundle: ad-hoc (`--sign -`) — a home-made certificate is not trusted on
# someone else's Mac anyway, ad-hoc is enough for arm64 code to run at all.
codesign --force --deep --sign - "$APP_DIR"

# Archive for distribution; the suffix (arm64/x86_64/universal) keeps archives of different architectures
# from overwriting each other when they are served from one place.
if [ -n "$ZIP_SUFFIX" ]; then
  ZIP_PATH="$OUT_DIR/$APP_NAME-macos-$ZIP_SUFFIX.zip"
else
  ZIP_PATH="$OUT_DIR/$APP_NAME-macos.zip"
fi
rm -f "$ZIP_PATH"
# --norsrc --noextattr: no AppleDouble (`._*`) entries in the archive. Homebrew's unzip would put them into the
# bundle and break the signature seal; --keepParent gives one top-level directory <APP_NAME>.app/.
ditto -c -k --norsrc --noextattr --keepParent "$APP_DIR" "$ZIP_PATH"

# Check of the archive: no AppleDouble or __MACOSX entries, exactly one top-level directory <APP_NAME>.app/.
if unzip -Z1 "$ZIP_PATH" | grep -Eq '(^|/)\._|__MACOSX'; then
  echo "archive $ZIP_PATH contains AppleDouble (._*) or __MACOSX entries" >&2
  exit 1
fi
ZIP_TOP="$(unzip -Z1 "$ZIP_PATH" | cut -d/ -f1 | sort -u)"
if [ "$ZIP_TOP" != "$APP_NAME.app" ]; then
  echo "archive $ZIP_PATH must have the single top-level directory $APP_NAME.app/, got: $ZIP_TOP" >&2
  exit 1
fi

echo "bundle: $APP_DIR"
echo "archive: $ZIP_PATH"
